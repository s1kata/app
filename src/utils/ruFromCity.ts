function heuristicGenitive(name: string): string {
  if (/[аА]$/.test(name)) return `${name.slice(0, -1)}ы`;
  if (/[яЯ]$/.test(name)) return `${name.slice(0, -1)}и`;
  if (/[ьЬ]$/.test(name)) return `${name.slice(0, -1)}и`;
  if (/[иыИЫ]$/.test(name) || /о$/i.test(name)) return name;
  if (/й$/i.test(name)) return `${name.slice(0, -1)}я`;
  if (/[бвгджзклмнпрстфхцчшщБВГДЖЗКЛМНПРСТФХЦЧШЩ]$/.test(name)) return `${name}а`;
  return name;
}

export function cityToGenitiveRu(city: string): string {
  const raw = (city || '').trim();
  if (!raw) return '';
  if (KNOWN_GENITIVE[raw]) return KNOWN_GENITIVE[raw];
  const folded = Object.keys(KNOWN_GENITIVE).find(
    (k) => k.toLowerCase() === raw.toLowerCase(),
  );
  if (folded) return KNOWN_GENITIVE[folded];
  return heuristicGenitive(raw);
}

/** «Из Самары» / EN: «From Samara» */
export function formatDepartureFrom(
  city: string | null | undefined,
  locale: string = 'ru',
): string {
  const name = (city || '').trim();
  if (!name) return '';
  const isRu = locale.toLowerCase().startsWith('ru');
  if (!isRu) return `From ${name}`;
  return `Из ${cityToGenitiveRu(name)}`;
}
